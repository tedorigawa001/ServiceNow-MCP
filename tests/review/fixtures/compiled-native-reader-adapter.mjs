import assert from 'node:assert/strict';
import {createInjectedNativeReaderOwner} from '../../../dist/servicenow/review-native-adapter.js';
globalThis.fetch=()=>{throw new Error('Network forbidden');};
const response=new Response(new Uint8Array([1,2,3]));
let dispatches=0;
const owner=createInjectedNativeReaderOwner({fake_io:true,deadline_ms:60000,budget:{read:()=>({remaining_ms:60000})},dispatch:()=>{dispatches++;return response;},schedule:(ms,wake)=>{const timer=setTimeout(wake,ms);return()=>clearTimeout(timer);}});
const acquired=await owner.acquire({purpose:'parent',ordinal:1,io_floor_ms:50250,cleanup_floor_ms:50000});
assert.equal(acquired.ok,true);
const {handle}=acquired.value;
assert.deepEqual((await owner.read(handle)).value,{done:false,value:new Uint8Array([1,2,3])});
assert.deepEqual((await owner.read(handle)).value,{done:true});
const finished=await owner.finish(handle);
assert.equal(finished.ok,true);
assert.equal(finished.value.body_eligible,false);
assert.equal(finished.value.evidence_issuance,'disabled');
assert.equal(finished.value.cleanup.disposition,'confirmed');
assert.equal(response.body.locked,false);
assert.equal(dispatches,1);
console.log('NA-02 compiled injected-native smoke PASS');
