import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url)),moduleName='abort-scope-evidence-http-classification';
const output=execFileSync('npm',['pack','--dry-run','--ignore-scripts','--offline','--json'],{cwd:root,encoding:'utf8',maxBuffer:8*1024*1024,env:{...process.env,npm_config_cache:join(tmpdir(),'servicenow-mcp-owner-pack-cache')},stdio:['ignore','pipe','pipe']});
const [pack]=JSON.parse(output);
for(const suffix of ['.js','.js.map','.d.ts','.d.ts.map'])assert(!pack.files.some(f=>f.path==='dist/review/'+moduleName+suffix));
assert(!pack.files.some(f=>f.path.startsWith('tests/')));
for(const f of pack.files.filter(f=>f.path.startsWith('dist/')&&f.path.endsWith('.js')))assert(!readFileSync(join(root,f.path),'utf8').includes(moduleName),'packaged runtime depends on development classifier: '+f.path);
execFileSync(process.execPath,[fileURLToPath(new URL('fixtures/compiled-http-classification.mjs',import.meta.url))],{cwd:root,stdio:'inherit'});
console.log('HTTP classification excluded; runtime unconnected; fixture/oracle excluded PASS ('+pack.files.length+' files)');
